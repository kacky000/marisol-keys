// End of the story: a slow credits roll over the game with the cast and their fates, then the
// island stays open for free roam.

import { CAST } from '../story/cast.js';

const FATES = {
  tessa: 'Bought Ozzie\'s boat. Runs sunset charters. Never on time.',
  ozzie: 'Retired to the bait shop. Claims it was his plan all along.',
  priya: 'Static 88 FM went legit. It is still the only honest station on the Keys.',
  lulu: 'The Coral Room hosts a race night every Friday. Tessa keeps losing on purpose.',
  gull: 'Testifying on the mainland. Crane Yard 7 is under new management.',
  hale: 'Awaiting trial. His estate pool was drained for evidence.',
};

export function rollCredits(onDone) {
  const el = document.createElement('div');
  el.id = 'credits';
  const people = Object.keys(FATES).map((k) => `<div class="credit"><b>${CAST[k].name}</b><span>${FATES[k]}</span></div>`).join('');
  el.innerHTML = `<div class="credits-inner"><h1>MARISOL KEYS</h1><h2>THE TIDE BOOK · THE END</h2>${people}
    <p class="credits-foot">Every street, car, face, song and sunset on this island was generated by the game itself.<br>The Keys are still yours — free roam continues.<br>Cab fares, paramedic runs, vigilante shifts, Tide pages and stunt ramps wait on the phone's Assets tab: one hundred percent pays.</p></div>`;
  document.body.appendChild(el);
  let closed = false;
  const close = () => { if (closed) return; closed = true; el.remove(); removeEventListener('keydown', key, true); onDone?.(); };
  // capture phase and stopImmediatePropagation: the key that closes the credits must not also
  // pause the game (Esc) or jump (Space)
  const key = (e) => {
    if (!el.isConnected) { close(); return; } // already taken down (quit to title): just unhook
    if (e.code !== 'Space' && e.code !== 'Escape' && e.code !== 'Enter') return;
    e.stopImmediatePropagation();
    close();
  };
  addEventListener('keydown', key, true);
  setTimeout(close, 26000);
}
